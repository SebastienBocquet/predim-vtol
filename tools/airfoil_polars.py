"""Generate ``src/predim_vtol/aero/airfoils.yaml``, the airfoil polars of the simple model.

The polars are computed by NeuralFoil (MIT licence, https://github.com/peterdsharpe/NeuralFoil)
on the airfoil coordinates of AeroSandbox (UIUC database, analytic NACA 4-digit). Neither
is a dependency of predim-vtol: run this script in an environment of its own::

    uv venv nf && uv pip install --python nf aerosandbox neuralfoil pyyaml
    nf/Scripts/python tools/airfoil_polars.py src/predim_vtol/aero/airfoils.yaml

For each Reynolds number, the pre-stall branch is kept (angles up to the maximum lift
coefficient, points with an analysis confidence of at least ``MIN_CONFIDENCE``), resampled
on a regular lift coefficient grid.
"""

from __future__ import annotations

import sys
from pathlib import Path

import aerosandbox as asb
import neuralfoil as nf
import numpy as np
import yaml

WING = {
    "SD7003": "sd7003",
    "SD7037": "sd7037",
    "E387": "e387",
    "E205": "e205",
    "MH32": "mh32",
    "MH45": "mh45",
    "S3021": "s3021",
    "RG15": "rg15",
    "AG35": "ag35",
    "ClarkY": "clarky",
    "NACA2412": "naca2412",
}
"""Wing airfoils: name in the project -> AeroSandbox name."""

STAB = {
    "NACA0006": "naca0006",
    "NACA0010": "naca0010",
    "NACA2406": "naca2406",
    "NACA2410": "naca2410",
}
"""Stabiliser airfoils, referenced by the stabiliser profile labels."""

REYNOLDS = (50_000, 100_000, 200_000, 400_000, 1_000_000)
ALPHA = np.arange(-8.0, 18.01, 0.25)
CL_STEP = 0.05
MIN_CONFIDENCE = 0.6
MODEL = "xlarge"


def polar(airfoil: asb.Airfoil, reynolds: float) -> dict:
    """The pre-stall polar of an airfoil at one Reynolds number, on the regular cl grid."""
    aero = nf.get_aero_from_airfoil(airfoil, alpha=ALPHA, Re=reynolds, model_size=MODEL)
    cl, cd, cm = (np.asarray(aero[k], dtype=float) for k in ("CL", "CD", "CM"))
    ok = np.asarray(aero["analysis_confidence"]) >= MIN_CONFIDENCE
    i_max = int(np.argmax(np.where(ok, cl, -np.inf)))
    i_min = int(np.argmin(np.where(ok, cl, np.inf)))
    branch = slice(i_min, i_max + 1)
    a, cl, cd, cm = ALPHA[branch], cl[branch], cd[branch], cm[branch]
    keep = np.concatenate([[True], np.diff(np.maximum.accumulate(cl)) > 0])
    a, cl, cd, cm = a[keep], cl[keep], cd[keep], cm[keep]
    grid = np.arange(np.ceil(cl[0] / CL_STEP) * CL_STEP, cl[-1] + 1e-9, CL_STEP)
    linear = (cl > 0.0) & (cl < 0.6 * cl[-1])
    slope, intercept = np.polyfit(np.radians(a[linear]), cl[linear], 1)
    return {
        "re": int(reynolds),
        "cl_max": round(float(cl[-1]), 4),
        "alpha0_deg": round(float(np.degrees(-intercept / slope)), 3),
        "cl_alpha": round(float(slope), 4),
        "cm0": round(float(np.mean(cm[linear])), 4),
        "cl": [round(float(x), 3) for x in grid],
        "cd": [round(float(x), 5) for x in np.interp(grid, cl, cd)],
    }


def airfoil_entry(name: str, source: str) -> dict:
    """The YAML entry of an airfoil: thickness, camber, polars at ``REYNOLDS``."""
    airfoil = asb.Airfoil(source)
    return {
        "thickness": round(float(airfoil.max_thickness()), 4),
        "camber": round(float(airfoil.max_camber()), 4),
        "polars": [polar(airfoil, re) for re in REYNOLDS],
    }


def main(path: Path) -> None:
    """Write the airfoil file."""
    data = {
        "source": (
            f"NeuralFoil {nf.__version__} ({MODEL}), AeroSandbox {asb.__version__} "
            "coordinates; generated by tools/airfoil_polars.py"
        ),
        "wing": {name: airfoil_entry(name, src) for name, src in WING.items()},
        "stab": {name: airfoil_entry(name, src) for name, src in STAB.items()},
    }
    header = "# Generated by tools/airfoil_polars.py: do not edit by hand.\n"
    path.write_text(
        header + yaml.safe_dump(data, sort_keys=False, width=100), encoding="utf-8"
    )


if __name__ == "__main__":
    main(Path(sys.argv[1]))
